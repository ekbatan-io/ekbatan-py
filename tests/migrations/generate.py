"""The suite's migration, one SQL file per dialect, generated from `fixtures.schema`.

Java's integration tests run Flyway over `V0001__create__events.sql`; this is that. It matters for
one reason beyond fidelity: **indexes are not in `ekbatan.schema`** and cannot be, because a single
declaration cannot be `WHERE delivered = FALSE` on PostgreSQL and a plain composite on MySQL. They
live wherever the table is created - here, and in each example's migrations - which is where Java
puts them too.

The table *shapes* still come from the metadata, because those are the contract other ports and
CDC connectors bind to, and transcribing them into DDL by hand is how the two drift. So the files
are generated, committed, and checked by `tests/unit/test_suite_migrations.py`: change the
metadata without regenerating and that test fails.

    uv run python tests/migrations/generate.py

MySQL and MariaDB share one directory: every type the schema uses has the same variant on both.
There the event tables are in a database of their own, ``eventlog``, and there is one per server -
so they are created once per server, from ``mysql-eventlog/`` (Java's
``V0000__create_eventlog_database.sql``, then the tables), and ``mysql/`` holds what each logical
database has of its own (``backends.MysqlFamilyBackend``).
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

#: Directory per dialect. MariaDB migrates from `mysql/`.
DIRECTORIES = {"sqlite": "sqlite", "postgres": "postgres", "mysql": "mysql", "mariadb": "mysql"}
FILE = "V0001__schema.sql"

#: MySQL's and MariaDB's `eventlog` database and the two event tables in it, created once per
#: server rather than per logical database.
EVENTLOG_DIRECTORY = "mysql-eventlog"
EVENTLOG_FILES = ("V0000__create_eventlog_database.sql", "V0001__eventlog.sql")

#: What the fan-out job asks for: undelivered rows of a type somebody subscribes to. On PostgreSQL
#: the predicate goes in the index, so it holds the backlog rather than the archive - measured at
#: 56 kB against 3,528 kB on 500,000 rows with a 1% backlog. MySQL and MariaDB have no partial
#: indexes, so the predicate column goes into the index instead.
UNDELIVERED = {
    "postgres": "CREATE INDEX ix_events_undelivered ON eventlog.events (event_type, event_date)"
    " WHERE delivered = FALSE;",
    "mysql": "CREATE INDEX ix_events_undelivered ON eventlog.events"
    " (delivered, event_type, event_date);",
    "sqlite": "CREATE INDEX ix_events_undelivered ON events (delivered, event_type, event_date);",
}

#: The table the action-id index goes on: in `eventlog`, a schema on PostgreSQL and a database on
#: MySQL and MariaDB; the file itself on SQLite (ekbatan.schema.eventlog_translation).
EVENTS_TABLE = {"postgres": "eventlog.events", "mysql": "eventlog.events", "sqlite": "events"}

#: What dispatch asks for: notifications still to deliver. SUCCEEDED and EXPIRED rows pile up and
#: are never selected, so on PostgreSQL they stay out of the index.
DUE = {
    "postgres": "CREATE INDEX ix_event_notifications_due"
    " ON eventlog.event_notifications (next_retry_at) WHERE state IN ('PENDING', 'FAILED');",
    "mysql": "CREATE INDEX ix_event_notifications_due ON eventlog.event_notifications"
    " (state, next_retry_at);",
    "sqlite": "CREATE INDEX ix_event_notifications_due ON event_notifications"
    " (state, next_retry_at);",
}

HEADER = (
    "-- Generated by tests/migrations/generate.py from tests/fixtures/schema.py. Do not edit:\n"
    "-- change the metadata and run `uv run python tests/migrations/generate.py`.\n\n"
)


def _clean(text: str) -> str:
    # SQLAlchemy ends each column line with a space; nothing downstream wants it.
    return "\n".join(line.rstrip() for line in text.split("\n"))


def _indexes(kind: str) -> str:
    """The event tables' indexes, which are not in the metadata (see the module notes)."""
    return (
        f"\nCREATE INDEX ix_events_action_id ON {EVENTS_TABLE[kind]} (action_id);\n\n"
        + UNDELIVERED[kind]
        + "\n\n"
        + DUE[kind]
        + "\n"
    )


def _split() -> tuple[Any, Any]:
    """The suite's metadata as two: the event tables, and everything else."""
    from sqlalchemy import MetaData

    from ekbatan.schema import EVENTLOG_SCHEMA
    from fixtures.schema import metadata

    eventlog, rest = MetaData(), MetaData()
    for table in metadata.sorted_tables:
        table.to_metadata(eventlog if table.schema == EVENTLOG_SCHEMA else rest)
    return eventlog, rest


def render(directory: str) -> str:
    """The `V0001__schema.sql` for one directory, as text."""
    from ekbatan.migrations import emit_ddl
    from fixtures.schema import metadata

    if directory == "mysql":
        # The event tables are the server's: `EVENTLOG_DIRECTORY` creates them, once.
        return _clean(HEADER + emit_ddl(_split()[1], "mysql"))
    return _clean(HEADER + emit_ddl(metadata, directory) + _indexes(directory))


def render_eventlog() -> dict[str, str]:
    """`EVENTLOG_DIRECTORY`'s files, by name: the database, then the tables in it."""
    from ekbatan.migrations import emit_ddl

    create, _, tables = emit_ddl(_split()[0], "mysql").partition("\n\n")
    assert create == "CREATE DATABASE IF NOT EXISTS eventlog;", create
    database, table_file = EVENTLOG_FILES
    return {
        database: HEADER + create + "\n",
        table_file: _clean(HEADER + tables + _indexes("mysql")),
    }


def files() -> dict[str, str]:
    """Every file the suite migrates from, by its path under `tests/migrations`."""
    found = {
        f"{directory}/{FILE}": render(directory) for directory in sorted(set(DIRECTORIES.values()))
    }
    found |= {f"{EVENTLOG_DIRECTORY}/{name}": text for name, text in render_eventlog().items()}
    return found


def main() -> None:
    for relative, text in files().items():
        target = HERE / relative
        target.parent.mkdir(exist_ok=True)
        target.write_text(text)
        print(f"wrote {target.relative_to(HERE.parent.parent)}")


if __name__ == "__main__":
    main()
