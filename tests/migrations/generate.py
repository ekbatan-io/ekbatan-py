"""The suite's migration, one SQL file per dialect, generated from `fixtures.schema`.

Java's integration tests run Flyway over `V0001__create__events.sql`; this is that. It matters for
one reason beyond fidelity: **indexes are not in `ekbatan.schema`** and cannot be, because a single
declaration cannot be `WHERE delivered = FALSE` on PostgreSQL and a plain composite on MySQL. They
live wherever the table is created - here, and in each example's migrations - which is where Java
puts them too.

The table *shapes* still come from the metadata, because those are the contract other ports and
CDC connectors bind to, and transcribing them into DDL by hand is how the two drift. So the files
are generated, committed, and checked by `tests/unit/test_suite_migrations.py`: change the
metadata without regenerating and that test fails.

    uv run python tests/migrations/generate.py

MySQL and MariaDB share one file: every type the schema uses has the same variant on both.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

#: Directory per dialect. MariaDB migrates from `mysql/`.
DIRECTORIES = {"sqlite": "sqlite", "postgres": "postgres", "mysql": "mysql", "mariadb": "mysql"}
FILE = "V0001__schema.sql"

#: What the fan-out job asks for: undelivered rows of a type somebody subscribes to. On PostgreSQL
#: the predicate goes in the index, so it holds the backlog rather than the archive - measured at
#: 56 kB against 3,528 kB on 500,000 rows with a 1% backlog. MySQL and MariaDB have no partial
#: indexes, so the predicate column goes into the index instead.
UNDELIVERED = {
    "postgres": "CREATE INDEX ix_events_undelivered ON events (event_type, event_date)"
    " WHERE delivered = FALSE;",
    "other": "CREATE INDEX ix_events_undelivered ON events (delivered, event_type, event_date);",
}

#: What dispatch asks for: notifications still to deliver. SUCCEEDED and EXPIRED rows pile up and
#: are never selected, so on PostgreSQL they stay out of the index.
DUE = {
    "postgres": "CREATE INDEX ix_event_notifications_due ON event_notifications (next_retry_at)"
    " WHERE state IN ('PENDING', 'FAILED');",
    "other": "CREATE INDEX ix_event_notifications_due ON event_notifications"
    " (state, next_retry_at);",
}


def render(directory: str) -> str:
    """The file for one directory, as text."""
    from ekbatan.migrations import emit_ddl
    from fixtures.schema import metadata

    kind = "postgres" if directory == "postgres" else "other"
    text = (
        "-- Generated by tests/migrations/generate.py from tests/fixtures/schema.py. Do not edit:\n"
        "-- change the metadata and run `uv run python tests/migrations/generate.py`.\n\n"
        + emit_ddl(metadata, directory)
        + "\nCREATE INDEX ix_events_action_id ON events (action_id);\n\n"
        + UNDELIVERED[kind]
        + "\n\n"
        + DUE[kind]
        + "\n"
    )
    # SQLAlchemy ends each column line with a space; nothing downstream wants it.
    return "\n".join(line.rstrip() for line in text.split("\n"))


def main() -> None:
    for directory in sorted(set(DIRECTORIES.values())):
        target = HERE / directory / FILE
        target.parent.mkdir(exist_ok=True)
        target.write_text(render(directory))
        print(f"wrote {target.relative_to(HERE.parent.parent)}")


if __name__ == "__main__":
    main()
