"""The complete-project-setup page shows the example projects' real files, and all of them.

The page imports each file from `ekbatan-py-examples/` when the site is built, so what it shows
cannot drift from code those examples test. What can still go wrong is which files it shows:
one added to an example and never put on the page, or a file the page shows once for every
database that stopped being the same in all three. Following the page end to end, with Docker,
is `scripts/check-setup-guide.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "website" / "src" / "pages" / "learn" / "complete-project-setup.mdx"
EXAMPLES = ROOT / "ekbatan-py-examples"
#: The page shows each database's uv project; its pip and Poetry twins hold the same files.
DATABASES = {
    "pg": "fastapi-wallet-rest-uv-pg/src/fastapi_wallet_rest_pg",
    "mysql": "fastapi-wallet-rest-uv-mysql/src/fastapi_wallet_rest_mysql",
    "mariadb": "fastapi-wallet-rest-uv-mariadb/src/fastapi_wallet_rest_mariadb",
}
#: Not on the page, each for a reason: generated by the page's own commands, or what only an
#: example inside this repository needs.
NOT_SHOWN = {"builders.py", "schema.py", "__init__.py", "__main__.py"}
SHARED = ("model.py", "converters.py", "actions.py", "handlers.py", "jobs.py", "api.py")

TEXT = PAGE.read_text()
IMPORTS = dict(re.findall(r'^import (\w+) from "([^"]+)\?raw";', TEXT, re.M))


def test_every_file_the_page_imports_exists() -> None:
    assert IMPORTS, "the page imports no example file"
    for name, path in IMPORTS.items():
        assert (PAGE.parent / path).resolve().is_file(), (name, path)


@pytest.mark.parametrize("name", SHARED)
def test_a_file_shown_once_is_the_same_in_all_three_examples(name: str) -> None:
    contents = {db: (EXAMPLES / example / name).read_text() for db, example in DATABASES.items()}
    assert len(set(contents.values())) == 1, f"{name} differs between the examples: {contents}"


@pytest.mark.parametrize(("db", "example"), DATABASES.items())
def test_the_page_shows_every_file_of_the_example(db: str, example: str) -> None:
    shown = {
        (PAGE.parent / path).resolve().relative_to(EXAMPLES / example).as_posix()
        for path in IMPORTS.values()
        if (PAGE.parent / path).resolve().is_relative_to(EXAMPLES / example)
    }
    if db != "pg":  # the shared files are imported from the PostgreSQL example
        shown |= set(SHARED)
    needed = {
        path.relative_to(EXAMPLES / example).as_posix()
        for path in (EXAMPLES / example).rglob("*")
        if path.is_file()
        and "__pycache__" not in path.parts
        and path.name not in NOT_SHOWN
        and not path.name.startswith(".")
    }
    assert shown == needed
