"""The complete-project-setup page shows the example projects' real files, and all of them.

The page imports each file from `ekbatan-py-examples/` when the site is built, so what it shows
cannot drift from code those examples test. What can still go wrong is which files it shows:
one added to an example and never put on the page, or a file the page shows once for several
databases or both modes that stopped being the same in all of them. Following the page end to
end, for every database, installer and mode, is `scripts/check-setup-guide.py`.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "website" / "src" / "pages" / "learn" / "complete-project-setup.mdx"
EXAMPLES = ROOT / "ekbatan-py-examples"

#: The examples the page builds - one per database and mode - each the uv project; their pip and
#: Poetry twins hold the same files.
SYNC_SERVER = {
    "pg": "fastapi-wallet-rest-uv-pg/src/fastapi_wallet_rest_pg",
    "mysql": "fastapi-wallet-rest-uv-mysql/src/fastapi_wallet_rest_mysql",
    "mariadb": "fastapi-wallet-rest-uv-mariadb/src/fastapi_wallet_rest_mariadb",
}
ASYNC_SERVER = {
    "pg": "fastapi-wallet-rest-uv-async-pg/src/fastapi_wallet_rest_async_pg",
    "mysql": "fastapi-wallet-rest-uv-async-mysql/src/fastapi_wallet_rest_async_mysql",
    "mariadb": "fastapi-wallet-rest-uv-async-mariadb/src/fastapi_wallet_rest_async_mariadb",
}
SQLITE = {
    "sync": "wallet-service-uv-sqlite/src/wallet_service_sqlite",
    "async": "wallet-service-uv-async-sqlite/src/wallet_service_async_sqlite",
}
ALL = [*SYNC_SERVER.values(), *ASYNC_SERVER.values(), *SQLITE.values()]

#: Shown once for the three server databases, because they are the same file in all three.
SHARED_SYNC = ("model.py", "converters.py", "actions.py", "handlers.py", "jobs.py", "api.py")
SHARED_ASYNC = (
    "model.py",
    "converters.py",
    "actions.py",
    "handlers.py",
    "api.py",
    "repository.py",
    "jobs.py",
)
MIGRATIONS = tuple(
    f"migrations/{name}.sql"
    for name in ("V0001__eventlog", "V0002__scheduled_tasks", "V0003__wallets", "V0004__alerts")
)

TEXT = PAGE.read_text()
IMPORTS = dict(re.findall(r'^import (\w+) from "([^"]+)\?raw";', TEXT, re.M))
SHOWN = {(PAGE.parent / path).resolve() for path in IMPORTS.values()}


def not_shown(example: str, name: str) -> bool:
    """Not on the page, each for a reason: generated by the page's own commands, or what only an
    example inside this repository needs. SQLite's schema and script are the project itself."""
    if name in ("builders.py", "__init__.py"):
        return True
    return name in ("schema.py", "__main__.py") and "sqlite" not in example


def same_name(name: str, other: str) -> bool:
    """`test_fastapi_wallet_rest_pg.py` and `test_fastapi_wallet_rest_async_pg.py` are one file
    of the page: `src/wallet/test_wallet.py`."""
    test = re.compile(r"(.*/)?test_[a-z_]+\.py")
    return name == other or bool(test.fullmatch(name) and test.fullmatch(other))


def test_every_file_the_page_imports_exists() -> None:
    assert IMPORTS, "the page imports no example file"
    for name, path in IMPORTS.items():
        assert (PAGE.parent / path).resolve().is_file(), (name, path)


@pytest.mark.parametrize("name", SHARED_SYNC)
def test_a_sync_file_shown_once_is_the_same_on_all_three_databases(name: str) -> None:
    contents = {db: (EXAMPLES / ex / name).read_text() for db, ex in SYNC_SERVER.items()}
    assert len(set(contents.values())) == 1, f"{name} differs between the examples"


@pytest.mark.parametrize("name", SHARED_ASYNC)
def test_an_async_file_shown_once_is_the_same_on_all_three_databases(name: str) -> None:
    contents = {db: (EXAMPLES / ex / name).read_text() for db, ex in ASYNC_SERVER.items()}
    assert len(set(contents.values())) == 1, f"{name} differs between the async examples"


@pytest.mark.parametrize("db", SYNC_SERVER)
@pytest.mark.parametrize("name", [*MIGRATIONS, "model.py", "converters.py"])
def test_a_file_shown_once_for_both_modes_is_the_same_in_both(db: str, name: str) -> None:
    sync, async_ = (EXAMPLES / SYNC_SERVER[db] / name), (EXAMPLES / ASYNC_SERVER[db] / name)
    assert sync.read_text() == async_.read_text(), f"{name} differs between the modes on {db}"


@pytest.mark.parametrize("name", ["schema.py", "model.py"])
def test_sqlite_files_shown_once_are_the_same_in_both_modes(name: str) -> None:
    sync = (EXAMPLES / SQLITE["sync"] / name).read_text()
    async_ = (EXAMPLES / SQLITE["async"] / name).read_text()
    assert sync == async_, f"{name} differs between the SQLite examples"


@pytest.mark.parametrize("example", ALL)
def test_the_page_shows_every_file_of_the_example(example: str) -> None:
    """Each file is on the page as itself, or as a byte-identical twin of another example's."""
    root = EXAMPLES / example
    missing = []
    for path in sorted(root.rglob("*")):
        name = path.relative_to(root).as_posix()
        if (
            not path.is_file()
            or "__pycache__" in path.parts
            or path.name.startswith(".")
            or not_shown(example, path.name)
        ):
            continue
        if path.resolve() in SHOWN:
            continue
        twins = [
            shown
            for shown in SHOWN
            if shown.read_bytes() == path.read_bytes()
            and same_name(name, shown.as_posix().rsplit("/src/", 1)[-1].split("/", 1)[-1])
        ]
        if not twins:
            missing.append(name)
    assert missing == [], f"{example}: not on the page: {missing}"
