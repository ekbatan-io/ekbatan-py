"""Every committed builder is the one `codegen` would write for today's model.

Java's annotation processor runs on every compile, so a generated builder there cannot be
stale or missing: the code does not build without it. Here the file is generated once and
committed, which is friendlier - no build step, and you can read the output - and leaves two
ways to be wrong that Java does not have:

**Missing.** A model with no generated builder still works. `copy()` falls back to the runtime
builder, which resolves setters by name, and nothing complains - you have quietly lost the type
checking the file existed to provide.

**Stale.** A model gains a field and the builder does not. The setter call is *not* caught,
because `ModelBuilder.__getattr__` accepts any name; `build()` then fails at runtime if the new
field is required, and silently takes the default if it is not.

This restores the guarantee by regenerating into memory and comparing, so `make lint` fails
where `javac` would.

    uv run python scripts/check-builders.py          # check
    uv run python scripts/check-builders.py --write  # regenerate the stale ones
"""

from __future__ import annotations

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

#: Where a package's models live, and where its builders belong beside them.
MODEL_FILE = "model.py"
BUILDER_FILE = "builders.py"

#: What `codegen` writes into its own header. A file without it was written by hand - the
#: website tells you to do that when a builder needs a conditional default or a computed
#: field - and comparing it against the generator would report it stale and offer to
#: overwrite it. Its existence is still checked; its contents are its author's business.
GENERATED_MARK = "Generated by `python -m ekbatan.codegen"

#: Packages that follow that convention: `<package>/model.py` beside `<package>/builders.py`.
#: The examples' uv projects - each package under its `src/`. Their pip and Poetry twins hold the
#: same files, which `scripts/sync-examples.py --check` holds them to.
TREES = sorted((ROOT / "ekbatan-py-examples").glob("*-uv-*/src"))

#: And the ones that do not put their models in `model.py`.
EXTRA = {ROOT / "tests" / "fixtures": "fixtures.domain"}


def packages() -> list[pathlib.Path]:
    return sorted(
        directory
        for tree in TREES
        if tree.is_dir()
        for directory in tree.iterdir()
        if (directory / MODEL_FILE).is_file()
    )


def formatted(source: str, name: str) -> str:
    """Through `ruff format`, so the comparison is about content rather than whitespace.

    `codegen` emits plain source and the committed files have been formatted, so a raw
    comparison called all seven stale on their import order.
    """
    for argv in (
        # `format` does not sort imports - that is the isort rule - and the committed files
        # have been through both, so both passes are needed or every file reads as stale.
        ["ruff", "check", "--select", "I", "--fix", "--quiet", "--stdin-filename", name, "-"],
        ["ruff", "format", "--stdin-filename", name, "-"],
    ):
        done = subprocess.run(argv, input=source, capture_output=True, text=True, check=False)
        if done.stdout:
            source = done.stdout
    return source


def main() -> int:
    write = "--write" in sys.argv
    for tree in TREES:
        sys.path.insert(0, str(tree))
    from ekbatan.codegen import generate

    missing: list[str] = []
    stale: list[str] = []
    by_hand: list[str] = []
    checked = 0

    sys.path.insert(0, str(ROOT / "tests"))
    for package in [*packages(), *EXTRA]:
        module = EXTRA.get(package) or f"{package.name}.{MODEL_FILE.removesuffix('.py')}"
        target = package / BUILDER_FILE
        want = formatted(generate([module], package=package.name), str(target))
        checked += 1

        if not target.exists():
            missing.append(str(target.relative_to(ROOT)))
            if write:
                target.write_text(want)
            continue

        have = target.read_text()
        if GENERATED_MARK not in have:
            by_hand.append(str(target.relative_to(ROOT)))
            continue
        if formatted(have, str(target)) != want:
            stale.append(str(target.relative_to(ROOT)))
            if write:
                target.write_text(want)

    verb = "regenerated" if write else "wrong"
    hand = f", {len(by_hand)} written by hand" if by_hand else ""
    print(f"{checked} builders checked, {len(missing) + len(stale)} {verb}{hand}")
    for path in missing:
        print(f"  MISSING  {path}  (run with --write)")
    for path in stale:
        print(f"  STALE    {path}  (run with --write)")
    for path in by_hand:
        print(f"  by hand  {path}  - present, contents not checked")
    return 0 if write or not (missing or stale) else 1


if __name__ == "__main__":
    sys.exit(main())
