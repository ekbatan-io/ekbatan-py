"""Generating typed builders, which is the one thing Python cannot infer for itself.

The runtime builder already works for every model there will ever be, and refuses an unknown
field at the point of the call. What it cannot do is tell a *type checker* that
``.balance(...)`` takes a ``Decimal``, because the setters are resolved by name at runtime and
a checker sees only ``__getattr__``.

Java solves this with an annotation processor that emits a ``WalletBuilder`` per model. This
does the same thing, for the same reason, and only for that reason: everything else the
processor does there - constructing, copying, incrementing a version - already needs no
generation here.

    python -m ekbatan.codegen myapp.model --out myapp/builders.py

The output is ordinary Python. Commit it, read it, and regenerate it when a model changes. The
first run works too, before the file exists, though the model already imports it.

Regenerating is not optional discipline, and this docstring used to imply it was: it claimed a
stale builder was "a type error rather than a silent wrong answer". Measured, it is neither.
A setter the builder does not declare is **not** caught by a checker - ``__getattr__`` on the
base accepts any name - and ``build()`` fails at runtime only if the new field is required,
taking the default silently if it is not. Java has no equivalent exposure: its processor runs
on every compile. ``scripts/check-builders.py`` restores that, in ``make lint``.
"""

from __future__ import annotations

import argparse
import contextlib
import dataclasses
import importlib
import importlib.util
import sys
import types
import typing
from collections.abc import Iterable, Iterator, Sequence
from pathlib import Path
from typing import Any

from .domain import Model, Persistable
from .repository import _concrete_types

__all__ = ["generate", "models_in"]

_BUILTIN = {"builtins", "typing"}


def models_in(module_names: Iterable[str]) -> list[type[Persistable[Any, Any]]]:
    """Every model and entity *defined* in these modules, in declaration order.

    Defined, not merely imported: generating a builder for something another module owns would
    put two of them in the codebase, and the second would go stale unnoticed.
    """
    found: list[type[Persistable[Any, Any]]] = []
    for name in module_names:
        module = importlib.import_module(name)
        for value in vars(module).values():
            if (
                isinstance(value, type)
                and issubclass(value, Persistable)
                and dataclasses.is_dataclass(value)
                and value.__module__ == name
                and value not in found
            ):
                found.append(value)
    return found


def generate(module_names: Iterable[str], *, package: str | None = None) -> str:
    """The source of a module of typed builders, one per model.

    ``package`` is the package the output will live in. Given it, imports from inside that
    package are emitted relative - which is what they have to be, or a checker sees the same
    file under two module names and refuses to go on.
    """
    modules = list(module_names)
    models = models_in(modules)
    if not models:
        raise SystemExit(f"no models or entities are defined in {modules}")

    imports: dict[str, set[str]] = {}
    quoted: dict[str, set[str]] = {}
    bodies: list[str] = []
    for model in models:
        bodies.append(_render(model, imports, quoted))

    for model in models:
        _need(quoted, model.__module__, model.__name__)

    # Two kinds of name are needed only by the checker, and both have to leave the runtime
    # imports or the file will not import at all:
    #
    #   - anything inside a quoted type argument, which is a string to the interpreter;
    #   - anything at all from the modules the models live in. Those modules import *this* one
    #     at the top, because a model names its builder on its class line, so importing them
    #     back would close the circle. Field annotations are strings here too, under
    #     `from __future__ import annotations`, so nothing needs them at runtime.
    for module in {m.__module__ for m in models}:
        quoted.setdefault(module, set()).update(imports.pop(module, set()))
    for module, checker_only in quoted.items():
        imports.get(module, set()).difference_update(checker_only)
    imports = {m: n for m, n in imports.items() if n}

    # The modules the models live in are imported for the checker only. Those modules import
    # *this* one, at the top, because a model names its builder on its class line - so
    # importing them back at runtime would close the circle. Nothing here needs them at
    # runtime: `builds` is filled in by `Persistable.__init_subclass__` when the model is
    # defined, and every annotation is a string under `from __future__ import annotations`.
    header = [
        '"""Typed builders. Generated by `python -m ekbatan.codegen ' + " ".join(modules) + "`.",
        "",
        "Regenerate this when a model gains or loses a field. A stale builder is a type error",
        "rather than a wrong answer: build() calls the real constructor, which will refuse.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for module in sorted(imports):
        names = ", ".join(sorted(imports[module]))
        header.append(f"from {_import_path(module, package)} import {names}")
    if quoted:
        header += ["", "if TYPE_CHECKING:"]
        for module in sorted(quoted):
            names = ", ".join(sorted(quoted[module]))
            # `noqa` because every use of these is inside a quoted type argument, and a linter
            # reading the file as source sees a string rather than a name.
            header.append(f"    from {_import_path(module, package)} import {names}  # noqa: F401")
    header.append("")
    return "\n".join(header) + "\n" + "\n\n".join(bodies) + "\n"


def _render(
    model: type[Persistable[Any, Any]],
    imports: dict[str, set[str]],
    quoted: dict[str, set[str]],
) -> str:
    name = model.__name__
    builder = f"{name}Builder"
    factory = _snake(name)

    base = "ModelBuilder" if issubclass(model, Model) else "EntityBuilder"
    _need(imports, "ekbatan.domain", base)
    resolved = _concrete_types(model)
    # Registered in `quoted`, not `imports`: these three reach the file only as the base's
    # type arguments, which are strings.
    id_type = _annotation(resolved.get("id", Any), quoted)
    state_type = _annotation(resolved.get("state", Any), quoted)
    _need(imports, "typing", "Self")
    _need(imports, "typing", "TYPE_CHECKING")

    article = "an" if name[0].lower() in "aeiou" else "a"
    inherited = (
        "id, state, version and the timestamps"
        if base == "ModelBuilder"
        else "id, state and version"
    )
    lines = [
        # Quoted, because these three names are imported for the checker only - see the
        # header. A checker resolves them; the interpreter never has to.
        f'class {builder}({base}["{name}", "{id_type}", "{state_type}"]):',
        f'    """Builds {article} {name}, with the field types a checker can see.',
        "",
        f"    {inherited} come from {base}, typed by the",
        f"    parameters above, so only the fields {name} added are declared here.",
        '    """',
        "",
        f'    builds_ref = "{model.__module__}:{name}"',
        "",
    ]
    for field, annotation in _fields(model):
        rendered = _annotation(annotation, imports)
        lines += [
            f"    def {field}(self, value: {rendered}) -> Self:",
            f"        return self.set({field}=value)",
            "",
        ]

    lines += [
        f"def {factory}(source: {name} | None = None) -> {builder}:",
        f'    """A fresh {builder}, optionally pre-loaded from an existing {name}."""',
        f"    made = {builder}()",
        "    return made.copy_base(source) if source is not None else made",
    ]
    return "\n".join(lines)


#: Declared by EntityBuilder and ModelBuilder, and typed there through their ID and state
#: parameters - so a generated builder never re-declares them, any more than Java's does.
_ON_THE_BASE = frozenset({"id", "state", "version"} | {f.name for f in dataclasses.fields(Model)})


def _fields(model: type[Persistable[Any, Any]]) -> Iterator[tuple[str, Any]]:
    """The fields this model added, and only those."""
    resolved = _concrete_types(model)
    for field in dataclasses.fields(model):
        if field.name in _ON_THE_BASE:
            continue
        yield field.name, resolved.get(field.name, Any)


def _annotation(hint: Any, imports: dict[str, set[str]]) -> str:
    """Render a resolved type back to source, collecting whatever it needs imported."""
    if hint is type(None):
        return "None"
    if hint is Any:
        _need(imports, "typing", "Any")
        return "Any"

    origin = typing.get_origin(hint)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_annotation(a, imports) for a in typing.get_args(hint))
    if origin is not None:
        args = ", ".join(_annotation(a, imports) for a in typing.get_args(hint))
        return f"{_annotation(origin, imports)}[{args}]" if args else _annotation(origin, imports)

    if isinstance(hint, type):
        if hint.__module__ not in _BUILTIN:
            _need(imports, hint.__module__, hint.__qualname__.split(".")[0])
        return hint.__qualname__
    if isinstance(hint, typing.NewType):
        # A label such as ekbatan.time.Instant: imported and written by its own name.
        _need(imports, hint.__module__, hint.__name__)
        return hint.__name__
    return "Any"


def _import_path(module: str, package: str | None) -> str:
    if package and (module == package or module.startswith(package + ".")):
        return "." + module[len(package) :].lstrip(".")
    return module


def _need(imports: dict[str, set[str]], module: str, name: str) -> None:
    if module != "builtins":
        imports.setdefault(module, set()).add(name)


def _snake(name: str) -> str:
    out: list[str] = []
    for index, char in enumerate(name):
        if char.isupper() and index:
            out.append("_")
        out.append(char.lower())
    return "".join(out)


def _infer_package(out: Path | None) -> str | None:
    """The dotted package an output path sits in, if it sits under the current directory."""
    if out is None:
        return None
    try:
        relative = out.resolve().relative_to(Path.cwd())
    except ValueError:
        return None
    parts = relative.parent.parts
    return ".".join(parts) if parts else None


def _package_holding(out: Path | None, modules: Sequence[str]) -> str | None:
    """The package whose directory ``out`` is written into, found from the modules being read.

    The current directory says nothing reliable here: under a ``src/`` layout - what ``uv init``
    and ``poetry new`` both create - ``src/wallet/builders.py`` would read as package
    ``src.wallet``. ``wallet.model`` says it is ``wallet``, and where ``wallet`` lives.
    """
    if out is None:
        return None
    directory = out.resolve().parent
    for name in modules:
        parent = name.rpartition(".")[0]
        while parent:
            spec = importlib.util.find_spec(parent)
            locations = spec.submodule_search_locations if spec is not None else None
            if locations and any(Path(p).resolve() == directory for p in locations):
                return parent
            parent = parent.rpartition(".")[0]
    return None


@contextlib.contextmanager
def _stand_in_for(module_name: str | None) -> Iterator[None]:
    """Stand in for the builders module while it does not exist yet - a project's first run.

    A model names its builder on its class line, so ``model.py`` imports ``builders.py`` - the
    file this command is about to write. Without this, the very first run fails on the import of
    its own output. Each name the model imports from it is an empty class for the duration;
    nothing is left behind, and once the file exists it is imported as it is.
    """
    if module_name is None or module_name in sys.modules:
        yield
        return
    try:
        exists = importlib.util.find_spec(module_name) is not None
    except ModuleNotFoundError:
        exists = False
    if exists:
        yield
        return
    stand_in = types.ModuleType(module_name)
    made: dict[str, type] = {}

    def __getattr__(name: str) -> type:
        if name.startswith("__"):
            raise AttributeError(name)
        return made.setdefault(name, type(name, (), {"builds": None, "builds_ref": None}))

    stand_in.__getattr__ = __getattr__  # type: ignore[method-assign]
    sys.modules[module_name] = stand_in
    try:
        yield
    finally:
        sys.modules.pop(module_name, None)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ekbatan.codegen",
        description="Generate typed builders for the models defined in one or more modules.",
    )
    parser.add_argument("modules", nargs="+", help="importable module names, e.g. myapp.model")
    parser.add_argument("--out", type=Path, help="where to write; stdout if omitted")
    parser.add_argument(
        "--package",
        help="the package the output lives in; imports from inside it are emitted relative. "
        "Inferred from --out when that path sits under the current directory.",
    )
    args = parser.parse_args(argv)

    package = args.package or _package_holding(args.out, args.modules) or _infer_package(args.out)
    target = f"{package}.{args.out.stem}" if package and args.out is not None else None
    with _stand_in_for(target):
        source = generate(args.modules, package=package)
    if args.out is None:
        sys.stdout.write(source)
    else:
        args.out.write_text(source)
        print(f"wrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
