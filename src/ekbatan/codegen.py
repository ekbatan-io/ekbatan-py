"""Generating typed builders, which is the one thing Python cannot infer for itself.

The runtime builder already works for every model there will ever be, and refuses an unknown
field at the point of the call. What it cannot do is tell a *type checker* that
``.balance(...)`` takes a ``Decimal``, because the setters are resolved by name at runtime and
a checker sees only ``__getattr__``.

Java solves this with an annotation processor that emits a ``WalletBuilder`` per model. This
does the same thing, for the same reason, and only for that reason: everything else the
processor does there - constructing, copying, incrementing a version - already needs no
generation here.

    python -m ekbatan.codegen myapp.model --out myapp/builders.py

The output is ordinary Python. Commit it, read it, and regenerate it when a model changes; a
stale one is a type error rather than a silent wrong answer, because ``build()`` still calls
the real constructor.
"""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import sys
import types
import typing
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

from .domain import Model, Persistable
from .repository import _concrete_types

__all__ = ["generate", "models_in"]

_BUILTIN = {"builtins", "typing"}


def models_in(module_names: Iterable[str]) -> list[type[Persistable[Any, Any]]]:
    """Every model and entity *defined* in these modules, in declaration order.

    Defined, not merely imported: generating a builder for something another module owns would
    put two of them in the codebase, and the second would go stale unnoticed.
    """
    found: list[type[Persistable[Any, Any]]] = []
    for name in module_names:
        module = importlib.import_module(name)
        for value in vars(module).values():
            if (
                isinstance(value, type)
                and issubclass(value, Persistable)
                and dataclasses.is_dataclass(value)
                and value.__module__ == name
                and value not in found
            ):
                found.append(value)
    return found


def generate(module_names: Iterable[str], *, package: str | None = None) -> str:
    """The source of a module of typed builders, one per model.

    ``package`` is the package the output will live in. Given it, imports from inside that
    package are emitted relative - which is what they have to be, or a checker sees the same
    file under two module names and refuses to go on.
    """
    modules = list(module_names)
    models = models_in(modules)
    if not models:
        raise SystemExit(f"no models or entities are defined in {modules}")

    imports: dict[str, set[str]] = {}
    bodies: list[str] = []
    for model in models:
        bodies.append(_render(model, imports))

    for model in models:
        _need(imports, model.__module__, model.__name__)

    header = [
        '"""Typed builders. Generated by `python -m ekbatan.codegen ' + " ".join(modules) + "`.",
        "",
        "Regenerate this when a model gains or loses a field. A stale builder is a type error",
        "rather than a wrong answer: build() calls the real constructor, which will refuse.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for module in sorted(imports):
        names = ", ".join(sorted(imports[module]))
        header.append(f"from {_import_path(module, package)} import {names}")
    header.append("")
    return "\n".join(header) + "\n" + "\n\n".join(bodies) + "\n"


def _render(model: type[Persistable[Any, Any]], imports: dict[str, set[str]]) -> str:
    name = model.__name__
    builder = f"{name}Builder"
    factory = _snake(name)

    base = "ModelBuilder" if issubclass(model, Model) else "EntityBuilder"
    _need(imports, "ekbatan.domain", base)
    resolved = _concrete_types(model)
    id_type = _annotation(resolved.get("id", Any), imports)
    state_type = _annotation(resolved.get("state", Any), imports)
    _need(imports, "typing", "Self")

    article = "an" if name[0].lower() in "aeiou" else "a"
    inherited = (
        "id, state, version and the timestamps"
        if base == "ModelBuilder"
        else "id, state and version"
    )
    lines = [
        f"class {builder}({base}[{name}, {id_type}, {state_type}]):",
        f'    """Builds {article} {name}, with the field types a checker can see.',
        "",
        f"    {inherited} come from {base}, typed by the",
        f"    parameters above, so only the fields {name} added are declared here.",
        '    """',
        "",
        f"    builds = {name}",
        "",
    ]
    for field, annotation in _fields(model):
        rendered = _annotation(annotation, imports)
        lines += [
            f"    def {field}(self, value: {rendered}) -> Self:",
            f"        return self.set({field}=value)",
            "",
        ]

    lines += [
        f"def {factory}(source: {name} | None = None) -> {builder}:",
        f'    """A fresh {builder}, optionally pre-loaded from an existing {name}."""',
        f"    made = {builder}()",
        "    return made.copy_from(source) if source is not None else made",
    ]
    return "\n".join(lines)


#: Declared by EntityBuilder and ModelBuilder, and typed there through their ID and state
#: parameters - so a generated builder never re-declares them, any more than Java's does.
_ON_THE_BASE = frozenset({"id", "state", "version"} | {f.name for f in dataclasses.fields(Model)})


def _fields(model: type[Persistable[Any, Any]]) -> Iterator[tuple[str, Any]]:
    """The fields this model added, and only those."""
    resolved = _concrete_types(model)
    for field in dataclasses.fields(model):
        if field.name in _ON_THE_BASE:
            continue
        yield field.name, resolved.get(field.name, Any)


def _annotation(hint: Any, imports: dict[str, set[str]]) -> str:
    """Render a resolved type back to source, collecting whatever it needs imported."""
    if hint is type(None):
        return "None"
    if hint is Any:
        _need(imports, "typing", "Any")
        return "Any"

    origin = typing.get_origin(hint)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_annotation(a, imports) for a in typing.get_args(hint))
    if origin is not None:
        args = ", ".join(_annotation(a, imports) for a in typing.get_args(hint))
        return f"{_annotation(origin, imports)}[{args}]" if args else _annotation(origin, imports)

    if isinstance(hint, type):
        if hint.__module__ not in _BUILTIN:
            _need(imports, hint.__module__, hint.__qualname__.split(".")[0])
        return hint.__qualname__
    return "Any"


def _import_path(module: str, package: str | None) -> str:
    if package and (module == package or module.startswith(package + ".")):
        return "." + module[len(package) :].lstrip(".")
    return module


def _need(imports: dict[str, set[str]], module: str, name: str) -> None:
    if module != "builtins":
        imports.setdefault(module, set()).add(name)


def _snake(name: str) -> str:
    out: list[str] = []
    for index, char in enumerate(name):
        if char.isupper() and index:
            out.append("_")
        out.append(char.lower())
    return "".join(out)


def _infer_package(out: Path | None) -> str | None:
    """The dotted package an output path sits in, if it sits under the current directory."""
    if out is None:
        return None
    try:
        relative = out.resolve().relative_to(Path.cwd())
    except ValueError:
        return None
    parts = relative.parent.parts
    return ".".join(parts) if parts else None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ekbatan.codegen",
        description="Generate typed builders for the models defined in one or more modules.",
    )
    parser.add_argument("modules", nargs="+", help="importable module names, e.g. myapp.model")
    parser.add_argument("--out", type=Path, help="where to write; stdout if omitted")
    parser.add_argument(
        "--package",
        help="the package the output lives in; imports from inside it are emitted relative. "
        "Inferred from --out when that path sits under the current directory.",
    )
    args = parser.parse_args(argv)

    source = generate(args.modules, package=args.package or _infer_package(args.out))
    if args.out is None:
        sys.stdout.write(source)
    else:
        args.out.write_text(source)
        print(f"wrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
